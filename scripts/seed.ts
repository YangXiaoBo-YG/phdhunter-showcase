async function seed() {
  console.log(`准备插入 ${jobs.length} 条测试数据...`);

  // 先清空已有数据（开发环境）
  const { error: delErr } = await supabase.from('jobs').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  if (delErr) {
    console.error('清空失败:', delErr.message);
    return;
  }

  // 分批插入（每批10条）
  const batchSize = 10;
  let inserted = 0;

  for (let i = 0; i < jobs.length; i += batchSize) {
    const batch = jobs.slice(i, i + batchSize);
    const { data, error } = await supabase.from('jobs').insert(batch).select('id');

    if (error) {
      console.error(`第 ${i + 1}-${i + batch.length} 条插入失败:`, error.message);
    } else {
      inserted += data.length;
      console.log(`已插入 ${inserted}/${jobs.length}`);
    }
  }

  // 验证
  const { count } = await supabase.from('jobs').select('*', { count: 'exact', head: true });
  console.log(`\n完成！数据库中共 ${count} 条岗位。`);

  // 维度统计
  const { data: stats } = await supabase.from('jobs').select('bianzhi_type, institution_type, location_city, position_type');
  if (stats) {
    const count_by = (key: string) => {
      const m: Record<string, number> = {};
      stats.forEach((r: Record<string, string>) => { m[r[key] || '空'] = (m[r[key] || '空'] || 0) + 1; });
      return m;
    };
    console.log('\n编制类型分布:', count_by('bianzhi_type'));
    console.log('机构类型分布:', count_by('institution_type'));
    console.log('城市分布:', count_by('location_city'));
    console.log('岗位类型分布:', count_by('position_type'));
  }
}

seed().catch(console.error);
