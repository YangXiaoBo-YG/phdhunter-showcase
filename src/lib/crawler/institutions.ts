/**
 * 根据机构名匹配 institution_type
 * 支持模糊匹配（机构名包含映射表中的关键词）
 */
export function matchInstitutionType(orgName: string): InstitutionType | null {
  // 精确匹配
  if (INSTITUTION_MAP[orgName]) {
    return INSTITUTION_MAP[orgName];
  }

  // 模糊匹配：遍历映射表，检查是否包含
  for (const [keyword, type] of Object.entries(INSTITUTION_MAP)) {
    if (orgName.includes(keyword) || keyword.includes(orgName)) {
      return type;
    }
  }

  // 关键词推断
  if (/大学|学院/.test(orgName) && /浙江|杭州|宁波|温州|金华|绍兴|湖州|台州|嘉兴|丽水|舟山|衢州/.test(orgName)) {
    return '普通本科'; // 浙江省内高校默认归为普通本科
  }

  if (/研究院|研究所|实验室/.test(orgName)) {
    if (/中国|中电|中核|中石|中航|国家电网|国网/.test(orgName)) {
      return '央企研究院';
    }
    if (/省|集团/.test(orgName)) {
      return '国企研究院';
    }
    return '科研院所';
  }

  if (/人社局|人社厅|事业单位/.test(orgName)) {
    return '事业单位';
  }

  return null;
}

